//! Builds `eval/results.md` (tables) and `eval/summary.json` from `eval/runs/*`.
//!
//! Runs are directories named after the model, plus `-categories` (the categories-only
//! variant on a sample), `-speed` (timing in a quiet window) and `-cpu` (CPU only).

use std::collections::{BTreeMap, HashSet};
use std::fmt::Write as _;
use std::fs;
use std::path::Path;
use std::process::ExitCode;

use serde_json::{Value, json};

use crate::eval_categorize::at_threshold;
use crate::td1::Score;

const THRESHOLDS: [u16; 8] = [0, 5000, 6000, 7000, 8000, 9000, 9500, 9900];
/// Whole-ledger correct with rules alone at the starting state (T2.2-BASELINE+T1.4, k=20).
const RULES_ONLY_CORRECT: usize = 4012;

fn read_json(path: &Path) -> Option<Value> {
    serde_json::from_slice(&fs::read(path).ok()?).ok()
}

fn read_lines(path: &Path) -> Vec<Value> {
    fs::read_to_string(path)
        .map(|s| {
            s.lines()
                .filter_map(|l| serde_json::from_str(l).ok())
                .collect()
        })
        .unwrap_or_default()
}

/// Peak memory from `/usr/bin/time` output, in bytes: macOS `-l` prints bytes
/// (`N  maximum resident set size`), GNU `-v` prints kilobytes
/// (`Maximum resident set size (kbytes): N`).
fn peak_rss(log: &Path) -> Option<u64> {
    let text = fs::read_to_string(log).ok()?;
    let line = text
        .lines()
        .find(|l| l.to_ascii_lowercase().contains("maximum resident set size"))?;
    if line.contains("(kbytes)") {
        let kb: u64 = line.rsplit(':').next()?.trim().parse().ok()?;
        Some(kb * 1024)
    } else {
        line.split_whitespace().next()?.parse().ok()
    }
}

fn pct(n: usize, d: usize) -> String {
    if d == 0 {
        "–".into()
    } else {
        format!("{:.1}%", 100.0 * n as f64 / d as f64)
    }
}

fn gb(bytes: u64) -> String {
    format!("{:.2} GB", bytes as f64 / 1e9)
}

fn num(v: &Value) -> usize {
    usize::try_from(v.as_u64().unwrap_or(0)).unwrap_or(0)
}

/// Starting whole-ledger score, summed over households.
fn start_score(variant_meta: &Value) -> Score {
    let mut s = Score::default();
    for h in variant_meta["households"].as_array().into_iter().flatten() {
        s.correct += num(&h["start"]["correct"]);
        s.wrong += num(&h["start"]["wrong"]);
        s.needs_review += num(&h["start"]["needs_review"]);
    }
    s
}

struct Speed {
    prefix_tok_s: f64,
    gen_tok_s: f64,
    median_ms: f64,
    per_100_s: f64,
}

fn speed(variant_meta: &Value, results: &[Value]) -> Speed {
    let t = &variant_meta["timings"];
    let per_s = |tokens: f64, ms: f64| if ms > 0.0 { tokens / ms * 1000.0 } else { 0.0 };
    let (mut prefix_tokens, mut prefix_ms) = (0.0, 0.0);
    for h in variant_meta["households"].as_array().into_iter().flatten() {
        prefix_tokens += h["prefix_tokens"].as_f64().unwrap_or(0.0);
        prefix_ms += h["prefix_ms"].as_f64().unwrap_or(0.0);
    }
    let mut ms: Vec<f64> = results.iter().filter_map(|r| r["ms"].as_f64()).collect();
    ms.sort_by(f64::total_cmp);
    let mean_ms = if ms.is_empty() {
        0.0
    } else {
        ms.iter().sum::<f64>() / ms.len() as f64
    };
    Speed {
        prefix_tok_s: per_s(prefix_tokens, prefix_ms),
        gen_tok_s: per_s(
            t["generated_tokens"].as_f64().unwrap_or(0.0),
            t["generated_ms"].as_f64().unwrap_or(0.0),
        ),
        median_ms: ms.get(ms.len() / 2).copied().unwrap_or(0.0),
        per_100_s: mean_ms / 10.0,
    }
}

fn counts(results: &[Value]) -> Score {
    let mut s = Score::default();
    for r in results {
        match r["outcome"].as_str() {
            Some("correct") => s.correct += 1,
            Some("wrong") => s.wrong += 1,
            _ => s.needs_review += 1,
        }
    }
    s
}

fn key(r: &Value) -> (String, i64) {
    (
        r["persona"].as_str().unwrap_or("").to_string(),
        r["id"].as_i64().unwrap_or(0),
    )
}

pub fn write(eval: &Path) -> ExitCode {
    let runs = eval.join("runs");
    let mut names: Vec<String> = fs::read_dir(&runs)
        .map(|d| {
            d.filter_map(Result::ok)
                .map(|e| e.file_name().to_string_lossy().into_owned())
                .collect()
        })
        .unwrap_or_default();
    names.sort();
    let is_model = |n: &&String| {
        !n.ends_with("-categories")
            && !n.contains("-speed")
            && !n.contains("-cpu")
            && n.as_str() != "oracle"
    };
    let models: Vec<&String> = names.iter().filter(is_model).collect();

    let mut md = String::from(
        "# T2.4 results\n\nGenerated by `fm-cli eval report` from `eval/runs/`. The analysis and recommendation are in `report.md`.\n",
    );
    let mut summary = BTreeMap::new();

    let _ = writeln!(
        md,
        "\n## Models\n\n| Model | Parameters | Licence | Provenance | File | SHA-256 | Peak memory | Load |\n|---|---|---|---|---|---|---|---|"
    );
    for m in &models {
        let Some(meta) = read_json(&runs.join(m).join("meta.json")) else {
            continue;
        };
        let rss = peak_rss(&runs.join(m).join("categorize.log"));
        let _ = writeln!(
            md,
            "| {m} | {} | {} | {} | {} | `{}` | {} | {:.1} s |",
            meta["parameters"].as_str().unwrap_or(""),
            meta["licence"].as_str().unwrap_or(""),
            meta["provenance"].as_str().unwrap_or(""),
            gb(meta["size"].as_u64().unwrap_or(0)),
            meta["sha256"].as_str().unwrap_or(""),
            rss.map_or_else(|| "–".to_string(), gb),
            meta["load_ms"].as_f64().unwrap_or(0.0) / 1000.0,
        );
    }
    let _ = writeln!(
        md,
        "\nPeak memory is the whole process on Metal: the weights (memory-mapped) plus the KV cache for a ~2,000-token prefix. Load includes checking the file's SHA-256."
    );

    let _ = writeln!(
        md,
        "\n## (a) Categorising what the rules left in review\n\nSPEC decision 45's choice set: the categories, income and uncategorised. Starting state: TD.1, transfer detection, rules and 20 corrections per household: {RULES_ONLY_CORRECT} of 7,376 correct, 30 wrong, 3,334 in review. Each model answers each of the 3,334, greedy and grammar-constrained.\n\n### On the 3,334 in review\n\n| Model | Answered | Correct | Wrong | Uncategorised | Errors | Contract violations | Fresh-context agreement |\n|---|---|---|---|---|---|---|---|"
    );
    let mut curves = BTreeMap::new();
    for m in &models {
        let Some(meta) = read_json(&runs.join(m).join("meta.json")) else {
            continue;
        };
        let Some(v) = meta["categorize"]["variants"]
            .as_array()
            .and_then(|vs| vs.iter().find(|v| v["variant"] == "categories+income"))
            .cloned()
        else {
            continue;
        };
        let results = read_lines(&runs.join(m).join("categories+income.jsonl"));
        let c = counts(&results);
        let n = results.len();
        let fresh = &v["fresh_context_agreement"];
        let _ = writeln!(
            md,
            "| {m} | {n} | {} ({}) | {} ({}) | {} ({}) | {} | {} | {}/{} |",
            c.correct,
            pct(c.correct, n),
            c.wrong,
            pct(c.wrong, n),
            c.needs_review,
            pct(c.needs_review, n),
            v["errors"],
            v["contract_violations"],
            fresh[0],
            fresh[1],
        );
        let start = start_score(&v);
        let curve: Vec<(u16, Score)> = THRESHOLDS
            .iter()
            .map(|&t| (t, at_threshold(&results, start, t)))
            .collect();
        curves.insert((*m).clone(), (curve, results, v));
    }

    let _ = writeln!(
        md,
        "\n### Whole ledger (7,376) by confidence threshold\n\nAnswers below the threshold stay in review. Each cell is correct / wrong; the rest is in review. Rules alone: {} correct, 0.4% wrong.\n",
        pct(RULES_ONLY_CORRECT, 7376)
    );
    let mut header = String::from("| Model |");
    let mut rule = String::from("|---|");
    for t in THRESHOLDS {
        let _ = write!(header, " ≥ {:.2} |", f64::from(t) / 10000.0);
        rule.push_str("---|");
    }
    let _ = writeln!(md, "{header}\n{rule}");
    for (m, (curve, _, _)) in &curves {
        let mut row = format!("| {m} |");
        for (_, s) in curve {
            let total = s.total();
            let _ = write!(
                row,
                " {} / {} |",
                pct(s.correct, total),
                pct(s.wrong, total)
            );
        }
        let _ = writeln!(md, "{row}");
    }

    let _ = writeln!(
        md,
        "\n### Calibration: how often an answer given is right, by its confidence\n\n| Model | < 0.50 | 0.50–0.80 | 0.80–0.95 | 0.95–0.99 | ≥ 0.99 |\n|---|---|---|---|---|---|"
    );
    for (m, (_, results, _)) in &curves {
        let bands = [
            (0, 5000),
            (5000, 8000),
            (8000, 9500),
            (9500, 9900),
            (9900, 10_001),
        ];
        let mut row = format!("| {m} |");
        for (lo, hi) in bands {
            let given: Vec<&Value> = results
                .iter()
                .filter(|r| matches!(r["outcome"].as_str(), Some("correct" | "wrong")))
                .filter(|r| (lo..hi).contains(&r["confidence_bp"].as_u64().unwrap_or(0)))
                .collect();
            let right = given.iter().filter(|r| r["outcome"] == "correct").count();
            let _ = write!(row, " {} of {} |", pct(right, given.len()), given.len());
        }
        let _ = writeln!(md, "{row}");
    }

    let _ = writeln!(
        md,
        "\n### What Income adds: categories only, on the same 1,000 (the first 250 in review per household)\n\n| Model | Categories only: correct / wrong | Categories + income: correct / wrong |\n|---|---|---|"
    );
    for m in &models {
        let only = read_lines(
            &runs
                .join(format!("{m}-categories"))
                .join("categories.jsonl"),
        );
        if only.is_empty() {
            continue;
        }
        let ids: HashSet<(String, i64)> = only.iter().map(key).collect();
        let with: Vec<Value> = read_lines(&runs.join(m).join("categories+income.jsonl"))
            .into_iter()
            .filter(|r| ids.contains(&key(r)))
            .collect();
        let (a, b) = (counts(&only), counts(&with));
        let _ = writeln!(
            md,
            "| {m} | {} / {} | {} / {} |",
            pct(a.correct, only.len()),
            pct(a.wrong, only.len()),
            pct(b.correct, with.len()),
            pct(b.wrong, with.len()),
        );
    }

    let _ = writeln!(
        md,
        "\n## Speed (Apple M2, 16 GB)\n\n`-speed` runs are 100 transactions (25 per household) on Metal, and `-cpu` runs 40 on the CPU only, in a quiet window; the others are the accuracy runs on a busy machine. `-cpu` runs use the build the app ships: no weight repacking, and on the CPU no flash attention and nothing sent to the GPU. `-cpu-repack` runs repack the weights: Qwen3.5-4B's on today's build otherwise, Ministral-3-3B's and Phi-4-mini's from an earlier build (flash attention on, large batches sent to this Mac's GPU), not re-measured.\n\n| Run | Prefix tokens/s | Generated tokens/s | Median per transaction | 100 transactions |\n|---|---|---|---|---|"
    );
    for name in names.iter().filter(|n| !n.ends_with("-categories")) {
        let Some(meta) = read_json(&runs.join(name).join("meta.json")) else {
            continue;
        };
        let Some(v) = meta["categorize"]["variants"]
            .as_array()
            .and_then(|v| v.first())
        else {
            continue;
        };
        let file = format!("{}.jsonl", v["variant"].as_str().unwrap_or(""));
        let sp = speed(v, &read_lines(&runs.join(name).join(file)));
        let _ = writeln!(
            md,
            "| {name} | {:.0} | {:.1} | {:.0} ms | {:.0} s |",
            sp.prefix_tok_s, sp.gen_tok_s, sp.median_ms, sp.per_100_s
        );
        summary.insert(
            format!("speed:{name}"),
            json!({"prefix_tok_s": sp.prefix_tok_s, "gen_tok_s": sp.gen_tok_s, "median_ms": sp.median_ms, "per_100_s": sp.per_100_s}),
        );
    }

    let _ = writeln!(
        md,
        "\n## (b) Question → query on TD.3\n\n**This is a floor, not T4.2's number.** Output is constrained only to well-formed JSON; T4.2 constrains it to T4.1's schema, which can only make more outputs valid. Every model gets the same prompt and the same 8 worked examples, chosen before any model ran and not scored: {}. Scored: the other 90 questions with an expected query. A query is read as `fm_core::query::Query`, run on the truth-labelled freelancer ledger, and counts as exact when every expected answer is matched by value (and by evidence ids for sums and counts). q062 and q065 are T4.1's known gaps (the right query can't give the answer yet), so they are listed apart and not held against a model.\n\n| Model | Valid JSON | Valid query | Ran | All answers exact (88) | Of them, proxies | Known gaps exact (2) | Median per question | p95 |\n|---|---|---|---|---|---|---|---|---|",
        crate::eval_query::FEW_SHOT.join(", ")
    );
    for m in &models {
        let rs = read_lines(&runs.join(m).join("queries.jsonl"));
        if rs.is_empty() {
            continue;
        }
        let count = |f: &dyn Fn(&Value) -> bool| rs.iter().filter(|r| f(r)).count();
        let n = rs.len();
        let scored: Vec<&Value> = rs.iter().filter(|r| r["known_gap"] != true).collect();
        let exact = scored.iter().filter(|r| r["exact"] == true).count();
        let proxies = scored.iter().filter(|r| r["proxy"] == true).count();
        let proxies_exact = scored
            .iter()
            .filter(|r| r["proxy"] == true && r["exact"] == true)
            .count();
        let gaps_exact = count(&|r| r["known_gap"] == true && r["exact"] == true);
        let mut ms: Vec<f64> = rs.iter().filter_map(|r| r["ms"].as_f64()).collect();
        ms.sort_by(f64::total_cmp);
        let at = |q: f64| {
            ms.get(((ms.len() as f64 - 1.0) * q).round() as usize)
                .copied()
                .unwrap_or(0.0)
        };
        let _ = writeln!(
            md,
            "| {m} | {} | {} | {} | {} ({}) | {proxies_exact} of {proxies} | {gaps_exact} | {:.1} s | {:.1} s |",
            pct(count(&|r| r["json"] == true), n),
            pct(count(&|r| r["query"] == true), n),
            pct(count(&|r| r["ran"] == true), n),
            exact,
            pct(exact, scored.len()),
            at(0.5) / 1000.0,
            at(0.95) / 1000.0,
        );
        summary.insert(
            format!("queries:{m}"),
            json!({"scored": scored.len(), "exact": exact, "valid_json": count(&|r| r["json"] == true), "valid_query": count(&|r| r["query"] == true), "ran": count(&|r| r["ran"] == true), "median_ms": at(0.5), "p95_ms": at(0.95)}),
        );
    }

    let _ = writeln!(
        md,
        "\n## (b) Proxy: sorting TD.3's questions into their types\n\nThe 20 `hard` questions are a difficulty bucket, not a type: timed, not scored.\n\n| Model | Correct of the 80 typed | Mean per question |\n|---|---|---|"
    );
    for m in &models {
        let Some(meta) = read_json(&runs.join(m).join("questions-meta.json")) else {
            continue;
        };
        let q = &meta["questions"];
        let _ = writeln!(
            md,
            "| {m} | {} ({}) | {:.0} ms |",
            q["correct"],
            pct(num(&q["correct"]), num(&q["scored"])),
            q["mean_ms"].as_f64().unwrap_or(0.0)
        );
        summary.insert(format!("questions:{m}"), q.clone());
    }

    for (m, (curve, results, v)) in &curves {
        let c = counts(results);
        summary.insert(
            format!("categorize:{m}"),
            json!({
                "review_set": {"n": results.len(), "correct": c.correct, "wrong": c.wrong, "uncategorised": c.needs_review},
                "errors": v["errors"], "contract_violations": v["contract_violations"],
                "whole_ledger_by_threshold": curve.iter().map(|(t, s)| json!({"threshold_bp": t, "correct": s.correct, "wrong": s.wrong, "needs_review": s.needs_review})).collect::<Vec<_>>(),
            }),
        );
    }

    fs::write(eval.join("results.md"), md).expect("write eval/results.md");
    fs::write(
        eval.join("summary.json"),
        serde_json::to_string_pretty(&summary).unwrap_or_default() + "\n",
    )
    .expect("write eval/summary.json");
    println!("wrote eval/results.md and eval/summary.json");
    ExitCode::SUCCESS
}
